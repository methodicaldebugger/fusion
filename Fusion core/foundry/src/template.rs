use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

#[derive(Debug, thiserror::Error)]
pub enum TemplateError {
    #[error("invalid project name '{0}': use letters, digits, '_' or '-', and start with a letter or '_'")]
    InvalidName(String),

    #[error("project already exists: {0}")]
    AlreadyExists(PathBuf),

    #[error("failed to create project at {path}: {source}")]
    Io {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

fn write_new_file(path: &Path, contents: &str) -> Result<(), TemplateError> {
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|source| TemplateError::Io {
            path: path.to_path_buf(),
            source,
        })?;

    file.write_all(contents.as_bytes())
        .map_err(|source| TemplateError::Io {
            path: path.to_path_buf(),
            source,
        })?;

    file.sync_all().map_err(|source| TemplateError::Io {
        path: path.to_path_buf(),
        source,
    })?;

    Ok(())
}

/// Creates a new Fusion project in `parent/name`.
///
/// Existing destinations are never overwritten.
pub fn create_project(parent: &Path, name: &str) -> Result<PathBuf, TemplateError> {
    if !is_valid_project_name(name) {
        return Err(TemplateError::InvalidName(name.to_owned()));
    }

    let root = parent.join(name);

    if root.exists() {
        return Err(TemplateError::AlreadyExists(root));
    }

    fs::create_dir(&root).map_err(|source| TemplateError::Io {
        path: root.clone(),
        source,
    })?;

    let result = create_project_contents(&root, name);

    if result.is_err() {
        // Roll back only this newly created project directory.
        // Never remove a directory that existed before this call.
        let _ = fs::remove_dir_all(&root);
    }

    result.map(|()| root)
}

fn is_valid_project_name(name: &str) -> bool {
    let mut chars = name.chars();

    let Some(first) = chars.next() else {
        return false;
    };

    (first.is_ascii_alphabetic() || first == '_')
        && chars.all(|ch| ch.is_ascii_alphanumeric() || ch == '_' || ch == '-')
}

fn create_project_contents(root: &Path, name: &str) -> Result<(), TemplateError> {
    for directory in ["src", "tests", "examples"] {
        let path = root.join(directory);

        fs::create_dir(&path).map_err(|source| TemplateError::Io { path, source })?;
    }

    let manifest = format!(
        r#"# Fusion project manifest
# Managed by Foundry.

[package]
name = "{name}"
version = "0.1.0"
"#
    );

    write_new_file(&root.join("Foundry.toml"), &manifest)?;

    // Initial lockfile: there are no dependencies to resolve yet.
    // The resolver can populate this file when dependency support is used.
    let lockfile = r#"# This file is generated by Foundry.
# It records resolved dependencies. Manual edits may be overwritten.
format = 1
"#;

    write_new_file(&root.join("foundry.lock"), lockfile)?;

    let gitignore = r#"# Foundry build output
/target/

# Local compiler and IDE artifacts
*.ll
*.o
*.obj
*.pdb
*.exe
*.dll
*.so
*.dylib

# Editor and operating-system files
.vscode/
.idea/
.DS_Store
Thumbs.db
"#;

    write_new_file(&root.join(".gitignore"), gitignore)?;

    let main_source = r#"// Fusion application entry point.
//
// Add your application code here.
// Keep this file compatible with the Fusion compiler version you use.

fn main() {
    print("Hello, world!");
}
"#;

    write_new_file(&root.join("src").join("main.fusion"), main_source)?;

    write_new_file(
        &root.join("tests").join("README.md"),
        "# Integration tests\n\nAdd Fusion integration test programs here.\n",
    )?;

    write_new_file(
        &root.join("examples").join("README.md"),
        "# Examples\n\nAdd runnable Fusion examples here.\n",
    )?;

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn temporary_parent() -> PathBuf {
        let nonce = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("system clock should be after Unix epoch")
            .as_nanos();

        std::env::temp_dir().join(format!(
            "foundry-template-test-{}-{nonce}",
            std::process::id()
        ))
    }

    #[test]
    fn creates_rust_style_fusion_project() {
        let parent = temporary_parent();
        fs::create_dir_all(&parent).unwrap();

        let root = create_project(&parent, "hello_world").unwrap();

        for relative in [
            "src",
            "tests",
            "examples",
            "Foundry.toml",
            "foundry.lock",
            ".gitignore",
            "src/main.fusion",
        ] {
            assert!(
                root.join(relative).exists(),
                "missing generated path: {relative}"
            );
        }

        let manifest = fs::read_to_string(root.join("Foundry.toml")).unwrap();
        assert!(manifest.contains(r#"name = "hello_world""#));
        assert!(manifest.contains(r#"version = "0.1.0""#));

        fs::remove_dir_all(parent).unwrap();
    }

    #[test]
    fn refuses_to_overwrite_existing_project() {
        let parent = temporary_parent();
        fs::create_dir_all(&parent).unwrap();

        let root = parent.join("hello_world");
        fs::create_dir(&root).unwrap();
        fs::write(root.join("keep.txt"), "preserve me").unwrap();

        let result = create_project(&parent, "hello_world");

        assert!(matches!(result, Err(TemplateError::AlreadyExists(_))));
        assert_eq!(
            fs::read_to_string(root.join("keep.txt")).unwrap(),
            "preserve me"
        );

        fs::remove_dir_all(parent).unwrap();
    }

    #[test]
    fn rejects_invalid_project_names() {
        assert!(!is_valid_project_name(""));
        assert!(!is_valid_project_name("../outside"));
        assert!(!is_valid_project_name("hello world"));
        assert!(is_valid_project_name("hello_world"));
        assert!(is_valid_project_name("hello-world2"));
    }
}
